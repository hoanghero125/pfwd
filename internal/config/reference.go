package config

import (
	"fmt"
	"strings"
	"time"
)

//go:generate go run ./gen ../../docs/config.md

// Setting is one key of config.toml as the reference documents it.
type Setting struct {
	// Key is the dotted path, such as forward.auto.
	Key string
	// Type is what the value is: true or false, an integer, a duration, a
	// string or a list.
	Type string
	// Default is the default value as TOML.
	Default string
	// Doc says what the setting does.
	Doc string
}

// Reference lists the settings of the [detect], [forward], [ssh] and [ui]
// tables, in the order Template writes them, with Template's comments.
func Reference() []Setting {
	var out []Setting
	table := ""
	for _, line := range strings.Split(Template(), "\n") {
		switch {
		case strings.HasPrefix(line, "["):
			table = strings.Trim(strings.Fields(line)[0], "[]")
		case strings.HasPrefix(line, "#"), strings.TrimSpace(line) == "":
		case table == "detect", table == "forward", table == "ssh", table == "ui":
			key, rest, ok := strings.Cut(line, "=")
			if !ok {
				continue
			}
			value, doc, _ := strings.Cut(rest, "#")
			value = strings.TrimSpace(value)
			out = append(out, Setting{Key: table + "." + strings.TrimSpace(key), Type: typeOf(value), Default: value, Doc: strings.TrimSpace(doc)})
		}
	}
	return out
}

// typeOf names a default value's type.
func typeOf(value string) string {
	switch {
	case value == "true" || value == "false":
		return "true or false"
	case strings.HasPrefix(value, "["):
		return "list"
	case strings.HasPrefix(value, `"`):
		if _, err := time.ParseDuration(strings.Trim(value, `"`)); err == nil {
			return "duration"
		}
		return "string"
	}
	return "integer"
}

// ReferenceMarkdown is docs/config.md: every setting, its default and what
// it does, plus the [labels] and [hosts.NAME] tables.
func ReferenceMarkdown() string {
	var b strings.Builder
	b.WriteString("<!-- Generated by go generate ./internal/config from internal/config/template.go; DO NOT EDIT. -->\n\n")
	b.WriteString(`# Configuration

pfwd reads one TOML file. ` + "`pfwd config path`" + ` prints where it is: ` + "`$XDG_CONFIG_HOME/pfwd/config.toml`" + ` (usually ` + "`~/.config/pfwd/config.toml`" + `) on Linux, ` + "`~/Library/Application Support/pfwd/config.toml`" + ` on macOS and ` + "`%APPDATA%\\pfwd\\config.toml`" + ` on Windows. ` + "`PFWD_CONFIG`" + ` or ` + "`--config`" + ` names another file.

Every setting is optional. ` + "`pfwd config edit`" + ` creates the file with every default and a comment on each line, and ` + "`pfwd config validate`" + ` reports unknown keys and bad values with their line numbers. The web UI's Settings page edits the common keys and the whole file. A running daemon uses a changed file after a restart.
`)
	table := ""
	for _, s := range Reference() {
		t, key, _ := strings.Cut(s.Key, ".")
		if t != table {
			table = t
			fmt.Fprintf(&b, "\n## [%s]\n\n| Setting | Type | Default | What it does |\n| --- | --- | --- | --- |\n", t)
		}
		fmt.Fprintf(&b, "| `%s` | %s | `%s` | %s |\n", key, s.Type, tableCell(s.Default), tableCell(sentence(s.Doc)))
	}
	b.WriteString(`
## [labels]

Names for ports, shown next to them in the TUI and the web UI. Your labels win over the built-in ones (Vite on 5173, Postgres on 5432, Jupyter on 8888 and so on).

` + "```toml" + `
[labels]
8000 = "API"
` + "```" + `

## [hosts.NAME]

Settings for one host, matched against its ssh config alias. They override the ones above for that host.

| Setting | Type | What it does |
| --- | --- | --- |
| ` + "`auto`" + ` | true or false | Forward new ports automatically on this host |
| ` + "`auto_ports`" + ` | list | Only auto-forward these ports and ranges on this host |
| ` + "`forwards`" + ` | list of strings | Forwards that are always on and pinned, in pfwd fwd's syntax: ` + "`\"5432\"`" + `, ` + "`\"15432:db.internal:5432\"`" + `, ` + "`\"-R 9000\"`" + `, ` + "`\"-D 1080\"`" + ` |

` + "```toml" + `
[hosts.devbox]
auto = false
forwards = ["5432", "15432:db.internal:5432", "-D 1080"]

[hosts.gpu-node]
auto_ports = [8888, 6006]
` + "```" + `
`)
	return b.String()
}

// tableCell escapes text for a Markdown table cell.
func tableCell(text string) string {
	return strings.ReplaceAll(text, "|", `\|`)
}

// sentence starts doc with a capital letter.
func sentence(doc string) string {
	if doc == "" {
		return ""
	}
	return strings.ToUpper(doc[:1]) + doc[1:]
}
